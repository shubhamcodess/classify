// Small DOM and formatting helpers shared by the pages.
import bench from "./bench-results.json";

export const $ = (s, el = document) => el.querySelector(s);
export const $$ = (s, el = document) => [...el.querySelectorAll(s)];
export const esc = (s) => String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
export const pct = (x) => `${Math.round(x * 100)}%`;
export const COLORS = ["#f7703f", "#7fd4a0", "#9db4ff", "#e8c46a", "#c39bff", "#f38ba8", "#6fd3c4", "#d7c9a7"];
export const colour = (i) => COLORS[Math.max(0, i) % COLORS.length];
export const sleep = () => new Promise((r) => setTimeout(r, 0));
export const mb = (bytes) => (bytes / 1048576).toFixed(1);

export function download(name, text, type) {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const a = Object.assign(document.createElement("a"), { href: url, download: name });
  document.body.append(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/** Measured benchmark, generated by `npm run bench` (src/bench-results.json). */
export const BENCH = bench;
export function benchMean(methodName) {
  const m = bench.methods.find((x) => x.name === methodName);
  if (!m) return null;
  const vals = Object.values(m.accuracy);
  return vals.reduce((a, b) => a + b, 0) / vals.length;
}
